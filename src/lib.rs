//! What the money and failure behaviour of the gateway **actually is**, measured.
//!
//! The two repositories this lab exists for make claims in their READMEs. Claims
//! become credible when someone else can reproduce the numbers, so this crate drives
//! the real `llmgateway` code — not a copy, not a mock of the gateway — with a fake
//! provider that can be told to fail in specific ways, and prints what happened.
//!
//! Three properties, because a measurement you cannot trust is worse than no
//! measurement:
//!
//! - **no network and no keys**: the provider is a trait implementation in this same
//!   process, so a full run takes milliseconds and never depends on someone else's
//!   availability or latency;
//! - **the invariants are assertions, not paragraphs**: `cargo test` fails if the cap
//!   stops holding or a denied request reaches the provider;
//! - **the numbers are in the repository**: `reports/latest.md` is generated by
//!   `make lab` and committed, so a reader can see the result before running anything.
//!
//! Scope limit, declared: this is the in-process core of the gateway. The HTTP
//! adapter and the agent side (an `agentloop` run driving this over the wire) are not
//! here yet — see the README.

